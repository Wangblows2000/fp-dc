#!/usr/bin/env python3
"""Write OBJECTS.md: every engine object type, the Fusion classes that map to it, its registry properties, the source
files that implement it and the ported levels that place it. Run after adding a level or an object type.

usage: tools/object_catalog.py [frames_dir=build/frames] [out=OBJECTS.md]

Sources: src/fp.h (OT_* enum), src/game/objdefs.c (registry rows), tools/import_frame.py (ENGINE_TYPES,
ENGINE_TYPES_ID), src/game/levels.c (level dirs + original frame index), <frames_dir>/frame_<index+1>.json."""
import json, os, re, sys, glob, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from import_frame import ENGINE_TYPES, ENGINE_TYPES_ID, engine_type

frames_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build', 'frames')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'OBJECTS.md')

fp = open(os.path.join(ROOT, 'src', 'fp.h')).read()
fp_nc = re.sub(r'/\*.*?\*/', '', fp, flags=re.S)   # every OT_ enum (the main one plus the per-file ranges >= 232)
body = '\n'.join(m.group(1) for m in re.finditer(r'enum\s*\{([^}]*)\}', fp_nc) if 'OT_' in m.group(1))
name = {}
for m in re.finditer(r'(OT_[A-Z0-9_]+)\s*=\s*(\d+)', body):
    if not m.group(1).endswith(('_FIRST', '_LAST')): name.setdefault(int(m.group(2)), m.group(1))
enum_val = {m.group(1): int(m.group(2)) for m in re.finditer(r'(OT_[A-Z0-9_]+)\s*=\s*(\d+)', body)}

defs = {}
for m in re.finditer(r'\{ (OT_[A-Z0-9_]+)(?: \+ (\d+))?,\s+([A-Z_|0-9]+),\s+(NULL|"[^"]*")\s+\}', open(os.path.join(ROOT, 'src', 'game', 'objdefs.c')).read()):
    t = enum_val[m.group(1)] + int(m.group(2) or 0)
    defs[t] = (m.group(3).replace('OD_', '').replace('|', ' ') if m.group(3) != '0' else '', m.group(4).strip('"') if m.group(4) != 'NULL' else '')

cls = collections.defaultdict(list)
for k, v in ENGINE_TYPES.items(): cls[v].append(k)
for (k, h), v in ENGINE_TYPES_ID.items(): cls[v].append('%s_%d' % (k, h))

srcs = [p for p in glob.glob(os.path.join(ROOT, 'src', '**', '*.[ch]'), recursive=True) + glob.glob(os.path.join(ROOT, 'src', '**', '*.inc'), recursive=True)
        if not p.endswith(('fp.h', 'objdefs.c'))]
text = {os.path.relpath(p, ROOT): open(p).read() for p in srcs}
def impl(t):
    n = name.get(t)
    if not n: return []
    rx = re.compile(r'\b%s\b' % n)
    return sorted(f.replace('src/', '') for f, s in text.items() if rx.search(s))

levels = re.findall(r'\{ (?:DV|AT)\("(\w+)", (\d+),', open(os.path.join(ROOT, 'src', 'game', 'levels.c')).read())
placed = collections.defaultdict(dict)
for lv, idx in levels:
    path = os.path.join(frames_dir, 'frame_%d.json' % (int(idx) + 1))
    if not os.path.exists(path): continue
    for o in json.load(open(path))['objects']:
        t = engine_type(o['cls'], o['id'])
        if t is None or o['x'] is None or o['x'] < 0 or o['y'] < 0: continue
        placed[t][lv] = placed[t].get(lv, 0) + 1

rows = []
for t in sorted(set(name) | set(defs) | set(cls)):
    n = name.get(t) or next((enum_val and '%s + %d' % (b, t - enum_val[b]) for b in ('OT_PARALLAX', 'OT_WR_LEG', 'OT_TD_PIECE') if b in enum_val and 0 < t - enum_val[b] < 12), '')
    fl, ens = defs.get(t, ('', ''))
    lv = ' '.join('%s:%d' % (k, v) for k, v in sorted(placed.get(t, {}).items()))
    rows.append('| %d | %s | %s | %s | %s | %s | %s |' % (t, n, ', '.join(sorted(cls.get(t, []))) or '(runtime)', fl, ens, ', '.join(impl(t)), lv))

with open(out, 'w') as f:
    f.write('''# Object catalogue (generated by tools/object_catalog.py; do not edit by hand)

One row per engine object type. **Classes**: the Fusion classes the importer maps to the type (ENGINE_TYPES; a class
with a handle suffix is a separate object that shares a class name, ENGINE_TYPES_ID). **Registry**: the shared
properties in src/game/objdefs.c (qualifier groups SOLID / OBSTACLE / NOEDGE, BOXCOL image-box collision) and the spawn
sprite. **Implemented in**: the source files that use the type. **Placed in**: on-map instances per ported level.

To use an existing object in a new level, place its class in that level (it is already in the original's frame data):
the importer types it, exports its sprites with the level's banks and the runtime runs it. See RE_NOTES "Reusable
objects and levels" for the per-level parameters some objects take from src/game/levels.c.

| Type | Enum | Classes | Registry | Sprite | Implemented in | Placed in |
|---|---|---|---|---|---|---|
''')
    f.write('\n'.join(rows) + '\n')
print('%s: %d types' % (out, len(rows)))
